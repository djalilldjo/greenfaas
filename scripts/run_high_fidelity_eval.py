"""
Run the full GreenFaaS evaluation on a high-fidelity Azure 2019 trace
generated by scripts/generate_high_fidelity_trace.py and a carbon model
calibrated to published 2020 regional means and amplitudes.

This is the closest we can get to running on the real Azure + ENTSO-E data
without network access to the multi-gigabyte real downloads. The trace
schema matches the public Azure 2019 dataset exactly; the carbon means
match the published 2020 statistics from ENTSO-E (DE, GB, FR) and CAISO
(US-CAISO). When real data becomes available, swap in the loaders without
code changes.
"""
from __future__ import annotations

import sys
import time
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from greenfaas import (
    CarbonModel,
    FifoScheduler,
    GreenFaaSScheduler,
    GreenFaaSV1Scheduler,
    Region,
    Simulator,
    SpatialScheduler,
    WaitAwhileScheduler,
    load_azure_2019_function_durations,
    load_azure_2019_invocation_counts,
    sample_invocations_from_2019,
)
from greenfaas.traces.azure_2021 import assign_regions_roundrobin

ROOT = Path(__file__).resolve().parents[1]
TRACE_DIR = ROOT / "sample_data" / "azure_2019_high_fidelity"


def build_regions(region_ids):
    rtt_pairs = {
        ("FR", "SE"): 35, ("FR", "DE"): 15, ("FR", "GB"): 12,
        ("FR", "US-CAISO"): 145, ("FR", "PL"): 30,
        ("SE", "DE"): 25, ("SE", "GB"): 30, ("SE", "US-CAISO"): 150, ("SE", "PL"): 30,
        ("DE", "GB"): 20, ("DE", "US-CAISO"): 155, ("DE", "PL"): 15,
        ("GB", "US-CAISO"): 140, ("GB", "PL"): 30,
        ("US-CAISO", "PL"): 170,
    }
    rtt_map = {r: {} for r in region_ids}
    for (a, b), v in rtt_pairs.items():
        if a in region_ids and b in region_ids:
            rtt_map[a][b] = float(v)
            rtt_map[b][a] = float(v)
    return {
        r: Region(region_id=r, name=r, capacity=1500,
                  network_rtt_ms=rtt_map[r], pue=1.2)
        for r in region_ids
    }


def main():
    region_ids = ["FR", "DE", "GB", "US-CAISO", "PL"]
    regions = build_regions(region_ids)

    print("=" * 72)
    print("GreenFaaS evaluation on high-fidelity Azure 2019 trace")
    print("=" * 72)
    print()
    print("Calibration sources:")
    print("  Workload: Shahrad et al. (USENIX ATC'20)")
    print("            trigger distribution, duration CDF, app-size CDF")
    print("  Carbon:   ENTSO-E (DE, GB, FR) + CAISO 2020 annual means")
    print("            with diurnal amplitudes from Wiesner et al. (Middleware'21)")
    print()

    # ----- Load trace ---------------------------------------------------- #
    print("[1/3] Loading high-fidelity Azure 2019 trace...")
    inv_path = next(TRACE_DIR.glob("invocations_per_function_md*.csv"))
    dur_path = next(TRACE_DIR.glob("function_durations_percentiles*.csv"))
    triggers, counts = load_azure_2019_invocation_counts(str(inv_path))
    durations = load_azure_2019_function_durations(str(dur_path))
    assignment = assign_regions_roundrobin(list(triggers.keys()), region_ids)
    invocations, functions = sample_invocations_from_2019(
        triggers, counts, durations,
        region_assignment=assignment,
        default_region=region_ids[0],
        seed=42,
    )
    print(f"  Loaded {len(invocations):,} invocations across {len(functions):,} functions")
    if not invocations:
        print("  ERROR: no invocations. Did you run generate_high_fidelity_trace.py?")
        sys.exit(1)

    duration_s = invocations[-1].arrival_time + 60.0
    print(f"  Simulated horizon: {duration_s/3600:.1f} hours")

    # Class breakdown
    class_counts = Counter(functions[i.function_id].latency_class.value
                           for i in invocations)
    print("  SLA class breakdown:")
    for cls, n in class_counts.most_common():
        print(f"    {cls:<12}: {n:>8,} invocations ({n / len(invocations):.1%})")

    # ----- Carbon model -------------------------------------------------- #
    print()
    print("[2/3] Building carbon model (literature-calibrated synthetic)...")
    carbon = CarbonModel.synthetic(region_ids, duration_s, step_s=300.0, seed=7)
    for r in region_ids:
        vals = carbon.traces[r].values
        mean = sum(vals) / len(vals)
        print(f"  {r:<10}: mean {mean:>6.1f} gCO2/kWh, "
              f"range [{min(vals):.0f}, {max(vals):.0f}]")

    # ----- Run all schedulers -------------------------------------------- #
    print()
    print("[3/3] Running 5 schedulers on identical workload...")
    schedulers = [
        FifoScheduler(),
        WaitAwhileScheduler(threshold_g=200.0, max_defer_s=1800.0),
        SpatialScheduler(max_rtt_ms=80.0),
        GreenFaaSV1Scheduler(forecast_accuracy="perfect", deferrable_rtt_ms=80.0),
        GreenFaaSScheduler(forecast_accuracy="perfect", deferrable_rtt_ms=80.0),
    ]
    results = []
    for sched in schedulers:
        t0 = time.time()
        sim = Simulator(regions=regions, functions=functions,
                        carbon=carbon, scheduler=sched)
        res = sim.run(invocations)
        elapsed = time.time() - t0
        results.append((sched.name, res, elapsed))
        s = res.summary()
        print(f"  {sched.name:<14}  carbon={s['carbon_g']:>8.2f}g  "
              f"SLA={s['sla_violation_rate']:>6.2%}  "
              f"cold={s['cold_start_rate']:>6.2%}  ({elapsed:.1f}s)")

    # ----- Report -------------------------------------------------------- #
    print()
    print("=" * 72)
    print("Headline results (high-fidelity trace)")
    print("=" * 72)
    print(f"{'scheduler':<14} {'carbon(g)':>10} {'vs FIFO':>9} {'SLA%':>7} "
          f"{'cold%':>7} {'p95(ms)':>10}")
    print("-" * 62)
    fifo_carbon = None
    for name, res, _ in results:
        s = res.summary()
        if fifo_carbon is None:
            fifo_carbon = s["carbon_g"]
        reduction = (fifo_carbon - s["carbon_g"]) / fifo_carbon * 100.0 if fifo_carbon else 0.0
        print(f"{name:<14} {s['carbon_g']:>10.2f} {reduction:>+8.2f}% "
              f"{s['sla_violation_rate']:>7.2%} {s['cold_start_rate']:>7.2%} "
              f"{s['p95_latency_ms']:>10.1f}")

    # ----- Sanity checks ------------------------------------------------- #
    fifo_carbon = results[0][1].summary()["carbon_g"]
    spatial_carbon = results[2][1].summary()["carbon_g"]
    gf_carbon = results[4][1].summary()["carbon_g"]
    print()
    print("Sanity checks:")
    print(f"  Wait-Awhile worse than FIFO? "
          f"{'YES (expected: pile-up failure)' if results[1][1].summary()['carbon_g'] > fifo_carbon else 'NO'}")
    print(f"  Spatial much better than FIFO? "
          f"{'YES (expected: low-carbon refuge)' if spatial_carbon < 0.5 * fifo_carbon else 'NO'}")
    print(f"  GreenFaaS close to Spatial? "
          f"{'YES (expected on full topology)' if abs(gf_carbon - spatial_carbon) < 0.1 * spatial_carbon else 'NO'}")


if __name__ == "__main__":
    main()
